#!/usr/bin/env python3
"""Build index.html (standalone / GitHub Pages) from marinaos.html.

marinaos.html is the Artifact page: it has no <html>/<head>/<body> of its
own because claude.ai wraps it at publish time. This script adds that wrapper
plus local-mode.js, so the same app runs from any static host.

Usage:  python3 build.py
"""
from pathlib import Path

root = Path(__file__).resolve().parent
app = (root / "marinaos.html").read_text(encoding="utf-8")

head = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
<!-- Generated by build.py from marinaos.html. Edit the source, then rebuild. -->
<style>
:root{color-scheme:light;padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}
body{margin:0;font:14px system-ui,-apple-system,"Segoe UI",sans-serif}
img{max-width:100%}
[hidden]{display:none!important}
</style>
<script src="local-mode.js"></script>
</head>
<body>
"""
(root / "index.html").write_text(head + app + "\n</body>\n</html>\n", encoding="utf-8")
print("Wrote index.html")
